/**
 * Build `lib/client.js` from `locales/ru.json`.
 *
 * The client half of a DSH browser plugin is not ESM: it hands a factory to
 * `window.__ModuleLoader__`. This script inlines the dictionaries into that
 * factory and validates them against the English source catalog extracted from
 * the shipped bundles, so a translation that loses or renames a `{placeholder}`
 * is reported before the pack is installed.
 *
 * Usage:
 *   node build.mjs            # rebuild lib/client.js
 *   node build.mjs --check    # validate only, write nothing
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));
const ru = JSON.parse(readFileSync(join(here, 'locales/ru.json'), 'utf8'));

// English source catalog, one JSON per namespace under locales/en/.
const enDir = join(here, 'locales/en');
const en = {};
if (existsSync(enDir)) {
  for (const f of readdirSync(enDir)) {
    if (f.endsWith('.json')) en[f.replace(/\.json$/, '')] = JSON.parse(readFileSync(join(enDir, f), 'utf8'));
  }
}

const problems = [];
const placeholders = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();

for (const [ns, dict] of Object.entries(ru)) {
  const source = en[ns];
  if (!source) {
    problems.push(`[${ns}] no English source catalog for this namespace`);
    continue;
  }
  for (const [key, value] of Object.entries(dict)) {
    if (!(key in source)) {
      problems.push(`[${ns}] ${key}: key does not exist in the English source`);
      continue;
    }
    const want = placeholders(source[key]);
    const got = placeholders(value);
    if (want.join(',') !== got.join(',')) {
      problems.push(`[${ns}] ${key}: placeholders {${want.join('} {')}} -> {${got.join('} {')}}`);
    }
  }
  const missing = Object.keys(source).filter((k) => !(k in dict));
  if (missing.length) problems.push(`[${ns}] untranslated keys (${missing.length}): ${missing.slice(0, 8).join(', ')}${missing.length > 8 ? ', …' : ''}`);
}

const totalKeys = Object.values(ru).reduce((a, d) => a + Object.keys(d).length, 0);
const totalSource = Object.values(en).reduce((a, d) => a + Object.keys(d).length, 0);
console.log(`namespaces: ${Object.keys(ru).length}   translated keys: ${totalKeys}   English source keys: ${totalSource}`);
for (const p of problems) console.log(`  ${p}`);
if (problems.length) console.log(`${problems.length} note(s)`);

if (process.argv.includes('--check')) process.exit(0);

const dictLiteral = Object.entries(ru)
  .map(([ns, dict]) => `\t\t\t${JSON.stringify(ns)}: ${JSON.stringify(dict, null, 4).replace(/\n/g, '\n\t\t\t')}`)
  .join(',\n');

const out = `window.__ModuleLoader__.load({
	id: ${JSON.stringify(pkg.name)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

		/**
		* Russian (ru) language pack for the DSH web GUI.
		*
		* Generated by build.mjs from locales/ru.json — edit that file, not this one.
		* Keys absent here fall back to English through the locale fallback chain.
		*/
		const LANGUAGE = { id: "ru", label: "Русский", fallback: "en" };
		const DICTS = {
${dictLiteral}
		};

		/** The locale service owns the catalog; this pack contributes to it. */
		const inject = ["locale"];

		function apply(ctx) {
			ctx.effect(
				() => ctx.locale.addLanguage(LANGUAGE),
				"locale-ru: language definition"
			);
			for (const [ns, dict] of Object.entries(DICTS)) {
				ctx.effect(
					() => ctx.locale.register(ns, LANGUAGE.id, dict),
					\`locale-ru: \${ns} dictionary\`
				);
			}
		}

		exports.apply = apply;
		exports.inject = inject;
		return module.exports;
	}
});
`;

writeFileSync(join(here, 'lib/client.js'), out, 'utf8');
console.log(`wrote lib/client.js (${out.length} bytes, ${Object.keys(ru).length} namespaces)`);
